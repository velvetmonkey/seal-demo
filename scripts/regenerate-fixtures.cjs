#!/usr/bin/env node
// Regenerate the published demo verdict fixtures through the shipped browser
// evaluator. Narrative fields remain filmed input; every verdict/cert is live.
const fs = require("node:fs");
const path = require("node:path");
const { webcrypto } = require("node:crypto");

const ROOT = path.resolve(__dirname, "..");
globalThis.require = require;
globalThis.__dirname = path.join(ROOT, "public/wasm");
globalThis.window = globalThis;
globalThis.crypto ||= webcrypto;
(0, eval)(fs.readFileSync(path.join(ROOT, "public/wasm/seal.js"), "utf8"));

const json = (value) => JSON.stringify(value, null, 2) + "\n";
const output = (file, value) => {
  const target = path.join(ROOT, "fixtures", file);
  const next = json(value);
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(target, "utf8") !== next) throw new Error(`${file} is stale; run node scripts/regenerate-fixtures.cjs`);
  } else fs.writeFileSync(target, next);
};

(async () => {
  const C = await import(path.join(ROOT, "public/seal-config.js"));
  const M = await globalThis.SealModule({
    locateFile: (p) => path.join(ROOT, "public/wasm", p), print() {}, printErr() {},
  });
  const decide = async (scenario) => {
    const signed = await C.buildSignedConfig(scenario.config);
    const init = JSON.parse(M.ccall("seal_init", "string", ["string", "string"], [signed.envelope, signed.pubkey]));
    if (init.ok !== true) throw new Error(`seal_init failed: ${init.error || JSON.stringify(init)}`);
    return C.parseVerdict(M.ccall("seal_decide", "string", ["string"], [C.buildStepInput(scenario)]), scenario.tool);
  };

  const results = {};
  for (const [key, scenario] of Object.entries(C.SCENARIOS)) results[key] = await decide(scenario);
  const cert = (key, kernel) => results[key].certs.find((c) => c.kernel === kernel);
  const compactCerts = (key) => results[key].certs.map(({ kernel, verdict, reason, certHash }) => ({ kernel, verdict, reason, certHash }));

  const captured = {
    _provenance: "Verdicts regenerated by scripts/regenerate-fixtures.cjs through the shipped df42 browser WASM and RFC 8032 Ed25519 test signer. No model in the loop.",
    demo1_determinism: ["destructive-sql", "self-approve", "wire-40k"].map((id) => ({
      id, tool: C.SCENARIOS[id].tool, arguments: C.SCENARIOS[id].args,
      verdict: results[id].verdict, deny_kernel: results[id].deny_kernel,
      reason: results[id].reason, certHash: results[id].certHash,
    })),
    demo2_policy_swap: {
      action: { tool: C.SCENARIOS["pay-before"].tool, arguments: C.SCENARIOS["pay-before"].args },
      before: { policy: "no quorum rule", verdict: results["pay-before"].verdict, certs: compactCerts("pay-before") },
      after: { policy: "consensus.high_stakes += payments.send", verdict: results["pay-after"].verdict, certs: compactCerts("pay-after") },
    },
    demo3_confident_hallucination: {
      tool: C.SCENARIOS["store-safe"].tool,
      safe: { arguments: C.SCENARIOS["store-safe"].args, verdict: results["store-safe"].verdict, convergence: cert("store-safe", "convergence") },
      subtle: { arguments: C.SCENARIOS["store-subtle"].args, verdict: results["store-subtle"].verdict, convergence: cert("store-subtle", "convergence") },
    },
  };

  const attack = JSON.parse(fs.readFileSync(path.join(ROOT, "fixtures/rm-rf-prod.json"), "utf8"));
  const attackConfig = { epoch: 1, safety: { approval: { control_file: "X", ttl_seconds: 120 }, tools: [{
    name: attack.tool_call.tool, mode: "guarded", match: { type: "always" }, target: [{ arg: "cmd" }],
  }] }, temporal: { policies: [] } };
  const attackResult = await decide({ config: attackConfig, tool: attack.tool_call.tool, args: attack.tool_call.args, approvals: [] });
  attack.expected_verdict = attackResult.verdict;
  if (attack.expected_verdict !== "DENY") throw new Error(`attack story drifted: expected DENY, got ${attack.expected_verdict}`);
  if (captured.demo2_policy_swap.before.verdict !== "ALLOW" || captured.demo3_confident_hallucination.safe.verdict !== "ALLOW")
    throw new Error("benign story drifted: expected ALLOW");

  const schema = JSON.parse(fs.readFileSync(path.join(ROOT, "fixtures/schema.json"), "utf8"));
  for (const key of schema.required || []) if (!(key in attack)) throw new Error(`rm-rf-prod.json missing schema field ${key}`);
  output("rm-rf-prod.json", attack);
  output("captured.json", captured);
  output("schema.json", schema);
  console.log(`fixtures ${process.argv.includes("--check") ? "current" : "regenerated"}: attack DENY; benign ALLOW`);
})().catch((error) => { console.error(error); process.exit(1); });
